"""
Версия: v0.1

Описание:
Первая версия раздела "Идея постов".

Что умеет:
- Реагировать на кнопку «💡 Идея постов».
- Хранить готовые идеи прямо в коде.
- Выбирать случайную идею из списка.
- Отправлять идею пользователю.

Что НЕ умеет:
- Хранить идеи в отдельном файле.
- Добавлять новые идеи через бота.
- Удалять идеи.
- Редактировать идеи.
- Искать идеи по категориям.
- Генерировать идеи с помощью ChatGPT.

Эта версия сохранена для будущего разбора.
"""

import random

from aiogram import F, Router
from aiogram.types import Message


router = Router()


post_ideas = [
    "💡 Расскажите историю одного из своих клиентов.",
    "💡 Покажите процесс своей работы.",
    "💡 Поделитесь полезным советом.",
    "💡 Ответьте на самый частый вопрос клиентов.",
    "💡 Покажите закулисье своей работы.",
    "💡 Развейте популярный миф в своей сфере.",
    "💡 Расскажите о своей самой большой ошибке и чему она вас научила.",
    "💡 Покажите результат своей работы «до» и «после».",
]


@router.message(F.text == "💡 Идея постов")
async def random_post_idea(message: Message):
    idea = random.choice(post_ideas)

    await message.answer(idea)